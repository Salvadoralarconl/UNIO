import {test,expect} from '@playwright/test';
import {writeFileSync} from 'node:fs';
let fixtureId:string|undefined;
test.afterEach(async({request})=>{if(fixtureId){await request.post(`http://127.0.0.1:5081/api/library/files/${fixtureId}/action`,{data:{operation:'delete'}});fixtureId=undefined;}});
test('Knowledge Base uploads, reviews, approves, and indexes a real file',async({page})=>{
  test.setTimeout(120000);
  const title=`Upload evaluation ${Date.now()}`;
  await page.goto('http://127.0.0.1:5174');
  await page.getByRole('tab',{name:'Documentation',exact:true}).click();
  await page.getByRole('button',{name:'Upload files',exact:true}).last().click();
  const dialog=page.getByRole('dialog',{name:'Upload files'});
  await dialog.getByLabel('Documentation file').setInputFiles({name:'evaluation.md',mimeType:'text/markdown',buffer:Buffer.from('# Evaluation fixture\n\nFor the fictional upload evaluation device, verify its test connection.\n')});
  await dialog.getByLabel('Document title').fill(title);
  await dialog.getByLabel('Version',{exact:true}).fill('test-1');
  const response=page.waitForResponse(r=>r.url().endsWith('/api/documents/upload')&&r.request().method()==='POST');
  await dialog.getByRole('button',{name:'Upload as draft'}).click();
  const uploadResponse=await response;
  expect(uploadResponse.ok(),await uploadResponse.text()).toBeTruthy();
  const uploaded=await uploadResponse.json();
  fixtureId=uploaded.id;
  writeFileSync('../artifacts/upload-evaluation-id.txt',uploaded.id);
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button',{name:`Open document ${title}`}).first().click();
  const reader=page.getByRole('region',{name:'Document reader'});
  await expect(reader).toContainText('draft');await expect(reader).toContainText('pending');
  await expect(page.locator('.wiki-content')).toContainText('fictional upload evaluation device');
  await reader.getByRole('button',{name:'Approve & index'}).click();
  await expect(reader.locator('.wiki-metadata')).toContainText('approved',{timeout:100000});
  await expect(reader.locator('.wiki-metadata')).toContainText('Indexed for Clary',{timeout:100000});
  await page.screenshot({path:'../artifacts/clary-knowledge-uploads.png',fullPage:true});
});
